import assert from 'node:assert/strict';
import { hasCurrentWeeklyCollection } from '../web/src/schedule.ts';
import { EMPTY_FILTERS, matchesFilters, matchesView, parseDate, procurementState } from '../web/src/opportunities.ts';
const now = Date.parse('2026-11-05T15:00:00Z');
assert.equal(hasCurrentWeeklyCollection('2026-11-06T22:26:00Z',Date.parse('2026-11-09T09:59:59Z')),true);
assert.equal(hasCurrentWeeklyCollection('2026-11-06T22:26:00Z',Date.parse('2026-11-09T10:00:00Z')),false);
assert.equal(hasCurrentWeeklyCollection('2026-11-09T11:00:00Z',Date.parse('2026-11-15T23:00:00Z')),true);
assert.equal(hasCurrentWeeklyCollection('2026-11-09T11:00:00Z',Date.parse('2026-11-16T10:00:00Z')),false);
assert.equal(hasCurrentWeeklyCollection('bad date',now),false);
const row = { id:'12345678000100-1-000001/2026', object:'Assinatura de plataforma para pesquisa de preços públicos', additionalInfo:'Planejamento de compras', organization:'Prefeitura de Belo Horizonte', state:'MG', city:'Belo Horizonte', modality:'Pregão - Eletrônico', score:70, suggestedOffer:'Public', proposalDeadline:'2026-11-07T12:00:00', statusId:1, instrumentId:1 };
assert.equal(+parseDate('2026-11-05T12:00:00'),now);
assert.equal(+parseDate('2026-11-05T15:00:00Z'),now);
assert.equal(+parseDate('2026-11-05T12:00:00-03:00'),now);
assert.equal(matchesFilters(row,{...EMPTY_FILTERS,query:'PREÇOS plataforma horizonte'},undefined,now),true);
assert.equal(matchesFilters(row,{...EMPTY_FILTERS,query:'preços microscópio'},undefined,now),false);
assert.equal(matchesFilters(row,{...EMPTY_FILTERS,uf:'SP'},undefined,now),false);
assert.equal(matchesFilters(row,{...EMPTY_FILTERS,deadline:'7'},undefined,now),true);
assert.equal(matchesFilters({...row,proposalDeadline:'2026-12-07T12:00:00'},{...EMPTY_FILTERS,deadline:'7'},undefined,now),false);
assert.equal(matchesView(row,'matches',undefined,now),true);
assert.equal(matchesView(row,'review',undefined,now),false);
assert.equal(matchesView({...row,score:40},'review',undefined,now),true);
assert.equal(matchesView({...row,learning:{label:'revisar',match:'similar_negative',reasonCode:'produto_diferente',examples:1}},'review',undefined,now),true);
assert.equal(matchesView(row,'matches',{offer:'Nenhuma',status:'Descartada',reason:'Outro produto'},now),false);
assert.equal(matchesView(row,'dismissed',{offer:'Nenhuma',status:'Descartada',reason:'Outro produto'},now),true);
assert.equal(matchesView({...row,score:40},'matches',{offer:'Public',status:'Em avaliação',reason:'Corresponde ao produto'},now),true);
assert.equal(procurementState({...row,statusId:2},now),'Inativa');
assert.equal(procurementState({...row,instrumentId:4},now),'Recebendo propostas');
assert.equal(matchesView({...row,instrumentId:4},'open',undefined,now),true);
assert.equal(matchesView({...row,instrumentId:3},'open',undefined,now),false);
assert.equal(matchesView({...row,statusId:2},'open',undefined,now),false);
assert.equal(procurementState({...row,proposalStart:'2026-11-06T12:00:00'},now),'A receber propostas');
assert.equal(procurementState({...row,proposalDeadline:'2026-11-04T12:00:00'},now),'Encerrada');
const ambiguous={...row,score:75,suggestedOffer:'Gerico',scores:{'Public':40,'Gerico':75}};
assert.equal(matchesFilters(ambiguous,{...EMPTY_FILTERS,product:'Public'},undefined,now),true);
assert.equal(matchesView(ambiguous,'review',undefined,now,'Public'),true);
assert.equal(matchesView(ambiguous,'matches',undefined,now,'Public'),false);
assert.equal(matchesView(ambiguous,'matches',undefined,now,'Gerico'),true);
